#!/usr/bin/env python3
"""
Builds ../PLM-Upgrade-ALL.sql: 10 + 20 + 25 + the two checks in ONE file that runs
in SSMS (no SQLCMD mode, no variables) or with sqlcmd -d <db>.

  * no USE statement: pick the database in SSMS (or sqlcmd -d) before running
  * aborts at the start if the selected database is not a PLM database
  * stops at the first failed batch (SET NOEXEC ON), so nothing runs after an error
  * every part is idempotent, so after fixing an error just run the whole file again

Usage (repo root):  python3 Deployment/Database/tools/build_single_script.py
"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
DB = os.path.join(HERE, '..')
OUT = os.path.join(DB, 'PLM-Upgrade-ALL.sql')
PARTS = [
    ('10-Upgrade-Schema.sql', 'Schema: missing tables and columns'),
    ('20-Upgrade-MasterData.sql', 'Master data: missing lookups, roles, settings'),
    ('25-EHC-Gap-MasterData.sql', 'EHC keys no seed script created'),
    ('90-Verify-Schema.sql', 'CHECK: missing tables/columns (both lists must be empty)'),
    ('30-Verify-MasterData.sql', 'CHECK: keys the code looks up that are still missing'),
]

HEADER = """/*
  PLM-Upgrade-ALL.sql  (GENERATED by tools/build_single_script.py, do not hand-edit)

  ONE script that brings an existing PLM database up to this release:
    1. schema      (10-Upgrade-Schema.sql)      missing tables and columns, additive only
    2. master data (20-Upgrade-MasterData.sql)  missing lookups/roles/settings, insert-only
    3. EHC gaps    (25-EHC-Gap-MasterData.sql)  EHC keys no seed script created
    4. checks      (90 + 30)                    result sets listing anything still missing

  HOW TO RUN (SSMS):
    a. Take a backup first (step 0 below shows the command).
    b. Open this file, choose the PLM database in the "Available Databases" drop-down
       (NOT master), press Execute. It takes a few minutes. Messages tab shows progress.
    c. It stops at the first error ("UPGRADE STOPPED ..."). Every part is safe to run
       twice, so fix the cause and run the whole file again.
  Or:  sqlcmd -S <server> -E -b -I -d <PLM database> -i PLM-Upgrade-ALL.sql

  Existing rows are never changed. New AppSettings rows carry dev values: review them with
  03-Review-Environment-Settings.sql. s_ceo is added as 0: set it to the CEO's Customers.Id.
*/

/* 0. BACKUP (run this line on its own first, edit the path):
   BACKUP DATABASE [<your PLM database>] TO DISK = N'D:\\Backups\\PLM_before_upgrade.bak' WITH COPY_ONLY, COMPRESSION;
*/
SET NOCOUNT ON;
SET NOEXEC OFF;
GO
IF DB_NAME() IN (N'master', N'model', N'msdb', N'tempdb')
   OR OBJECT_ID(N'dbo.PropertyLeaseApplications', 'U') IS NULL
   OR OBJECT_ID(N'dbo.AppSettings', 'U') IS NULL
BEGIN
    DECLARE @db sysname = DB_NAME();
    RAISERROR('UPGRADE STOPPED: the selected database (%s) is not a PLM database. Pick the PLM database and run again.', 16, 1, @db) WITH NOWAIT;
    SET NOEXEC ON;
END
GO
IF OBJECT_ID('tempdb..#upgrade_ok') IS NOT NULL DROP TABLE #upgrade_ok;
CREATE TABLE #upgrade_ok (n int PRIMARY KEY);
DECLARE @msg nvarchar(300) = N'Upgrading ' + DB_NAME() + N' on ' + @@SERVERNAME + N' at ' + CONVERT(nvarchar(30), SYSDATETIME(), 120);
RAISERROR(@msg, 0, 1) WITH NOWAIT;
GO
"""

GUARD = """IF OBJECT_ID('tempdb..#upgrade_ok') IS NULL OR NOT EXISTS (SELECT 1 FROM #upgrade_ok WHERE n = {n})
BEGIN
    IF @@TRANCOUNT > 0 ROLLBACK;
    RAISERROR('UPGRADE STOPPED in part "{part}" (batch {n}). Read the error above, fix it, then run the whole file again (it is safe to re-run).', 16, 1) WITH NOWAIT;
    SET NOEXEC ON;
END
GO
"""


def batches(sql):
    """Split on GO lines; drop USE [$(DbName)] lines."""
    sql = re.sub(r'^\s*USE \[\$\(DbName\)\];\s*$', '', sql, flags=re.M)
    return [b for b in re.split(r'^\s*GO\s*$', sql, flags=re.M) if b.strip()]


def main():
    out, n = [HEADER], 0
    for fname, title in PARTS:
        src = open(os.path.join(DB, fname), encoding='utf-8-sig').read()
        assert '$(' not in re.sub(r'/\*.*?\*/', '', src, flags=re.S).replace('USE [$(DbName)];', ''), fname
        out.append('\n/' + '*' * 78 + '\n   PART: %s  (%s)\n' % (title, fname) + '*' * 78 + '/\n')
        out.append("RAISERROR('--- %s ---', 0, 1) WITH NOWAIT;\nGO\n" % title.replace("'", "''"))
        for b in batches(src):
            n += 1
            # The last statement of each batch records success; a batch that fails never gets there.
            out.append(b.rstrip() + '\nINSERT #upgrade_ok VALUES (%d);\nGO\n' % n)
            out.append(GUARD.format(n=n, part=fname))
    out.append("RAISERROR('UPGRADE FINISHED. Check the result grids: missing tables/columns must be empty.', 0, 1) WITH NOWAIT;\nGO\nSET NOEXEC OFF;\nGO\n")
    with open(OUT, 'w', encoding='utf-8', newline='\r\n') as f:
        f.write(''.join(out))
    print('wrote', os.path.abspath(OUT), n, 'batches')


if __name__ == '__main__':
    main()
